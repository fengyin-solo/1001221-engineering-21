def _row(row_id: int, status: str, pending: bool, abnormal: bool, **fields: Any) -> dict[str, Any]:
    row: dict[str, Any] = {
        "id": row_id,
        "status": status,
        "pending": pending,
        "abnormal": abnormal,
    }
    row.update(fields)
    return row


